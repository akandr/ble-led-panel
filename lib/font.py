def text_width(s, font=F3, gap=1):
    w = 0
    for ch in s:
        g = font.get(ch.upper() if font is F3 else ch, font[' '])
        w += len(g[0]) + gap
    return w - gap if s else 0

def draw_text(px, x, y, s, color, font=F3, gap=1, W=64, H=16):
    """Draw string s at (x,y) with pixel access px; returns x after last glyph."""
    for ch in s:
        key = ch.upper() if font is F3 else ch
        g = font.get(key, font[' '])
        for r, row in enumerate(g):
            for c, b in enumerate(row):
                if b == "1" and 0 <= x + c < W and 0 <= y + r < H:
                    px[x + c, y + r] = color(x + c, y + r) if callable(color) else color
        x += len(g[0]) + gap
    return x
